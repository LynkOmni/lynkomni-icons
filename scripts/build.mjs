#!/usr/bin/env node
// Builds every LynkOmni brand output from src/logos/*.svg + brand/*.json.
// No dependencies. Deterministic: the same inputs always produce byte-identical files.
// Usage: node scripts/build.mjs            (writes ./dist)

import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSvg, viewBoxOf, drawTree, geometrySignature } from './lib/svg.mjs';
import { addIconFiles } from './icons.mjs';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SVG_NS = 'http://www.w3.org/2000/svg';
const GENERATED = 'Generated by @lynkomni/icons (scripts/build.mjs). Do not edit by hand.';

export const THEME_VARIANTS = ['light', 'dark', 'contrast-light', 'contrast-dark'];
export const ALL_VARIANTS = [...THEME_VARIANTS, 'mono'];

const SUFFIX = { light: 'Light', dark: 'Dark', 'contrast-light': 'ContrastLight', 'contrast-dark': 'ContrastDark', mono: 'Mono', auto: 'Auto' };
// Themed ("auto") shapes read the platform design tokens (--logo-ink, then --text-primary, and --brand-primary),
// so they follow every theme with no JavaScript.
const TOKEN_FOR_ROLE = { ink: '--logo-ink', accent: '--brand-primary' };

export function loadConfig(root = ROOT) {
  const manifest = JSON.parse(readFileSync(join(root, 'brand/manifest.v1.json'), 'utf8'));
  const themes = JSON.parse(readFileSync(join(root, 'brand/themes.v1.json'), 'utf8')).themes;
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  return { manifest, themes, pkg };
}

export function palette(themes) {
  if (themes.light.accent !== themes.dark.accent) throw new Error('Light and dark must share the same accent colour');
  return { accent: themes.light.accent, ink: [themes.light.ink, themes.dark.ink] };
}

export function loadAsset(root, asset, themes) {
  const pal = palette(themes);
  const read = (theme) => {
    const svg = parseSvg(readFileSync(join(root, asset.sources[theme]), 'utf8'));
    return { svg, vb: viewBoxOf(svg), tree: drawTree(svg, pal) };
  };
  const light = read('light');
  const dark = read('dark');
  if (geometrySignature(light.tree) !== geometrySignature(dark.tree)) {
    throw new Error(`${asset.id}: light and dark artwork differ in shape, not only in colour`);
  }
  // Light and dark files were saved with different padding. The artwork is identical, so use one view box.
  return { tree: light.tree, vb: light.vb };
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const num = (n) => String(Math.round(n * 100) / 100);

function colourFor(variant, role, themes) {
  return variant === 'mono' ? 'currentColor' : themes[variant][role];
}

// ---------- SVG ----------
function svgOf(tree, vb, label, colour) {
  const body = (items) =>
    items
      .map((it) => {
        if (it.kind === 'path') {
          return `<path fill="${colour(it.role)}"${it.evenodd ? ' fill-rule="evenodd"' : ''} d="${it.d}"/>`;
        }
        const t = it.tx || it.ty ? ` transform="translate(${num(it.tx)} ${num(it.ty)})"` : '';
        return `<g${t}>${body(it.items)}</g>`;
      })
      .join('');
  return `<svg xmlns="${SVG_NS}" viewBox="${vb.join(' ')}" role="img" aria-label="${esc(label)}" focusable="false">${body(tree)}</svg>\n`;
}

function faviconSvg(tree, vb, themes) {
  const body = (items) =>
    items
      .map((it) => {
        if (it.kind === 'path') return `<path class="${it.role === 'ink' ? 'i' : 'a'}"${it.evenodd ? ' fill-rule="evenodd"' : ''} d="${it.d}"/>`;
        return `<g>${body(it.items)}</g>`;
      })
      .join('');
  const style = `.i{fill:${themes.light.ink}}.a{fill:${themes.light.accent}}@media (prefers-color-scheme:dark){.i{fill:${themes.dark.ink}}}`;
  return `<svg xmlns="${SVG_NS}" viewBox="${vb.join(' ')}"><style>${style}</style>${body(tree)}</svg>\n`;
}

const themedFill = (role, fallback) =>
  role === 'ink' ? `var(--logo-ink, var(--text-primary, ${fallback}))` : `var(${TOKEN_FOR_ROLE[role]}, ${fallback})`;

// ---------- React (plain JS, no JSX, so it works in any bundler and on the server) ----------
function reactOf(name, tree, vb, label, colour, themed) {
  const node = (it, indent) => {
    const pad = '  '.repeat(indent);
    if (it.kind === 'path') {
      const attrs = [`d: ${JSON.stringify(it.d)}`];
      if (themed) attrs.push(`style: { fill: ${JSON.stringify(themedFill(it.role, colour(it.role)))} }`);
      else attrs.push(`fill: ${JSON.stringify(colour(it.role))}`);
      if (it.evenodd) attrs.push("fillRule: 'evenodd'");
      return `${pad}h('path', { ${attrs.join(', ')} })`;
    }
    const props = it.tx || it.ty ? `{ transform: 'translate(${num(it.tx)} ${num(it.ty)})' }` : 'null';
    return `${pad}h('g', ${props},\n${it.items.map((c) => node(c, indent + 1)).join(',\n')}\n${pad})`;
  };
  return `// ${GENERATED}
import { createElement as h } from 'react';

export function ${name}(props) {
  return h(
    'svg',
    {
      xmlns: '${SVG_NS}',
      viewBox: '${vb.join(' ')}',
      role: 'img',
      'aria-label': ${JSON.stringify(label)},
      focusable: 'false',
      ...props,
    },
${tree.map((it) => node(it, 3)).join(',\n')}
  );
}

export default ${name};
`;
}

// ---------- Android ----------
function androidOf(tree, vb, colour, heightDp = 48) {
  const [minX, minY, w, hgt] = vb;
  const widthDp = num((heightDp * w) / hgt);
  const argb = (hex) => (hex === 'currentColor' ? '#FF000000' : '#FF' + hex.slice(1).toUpperCase());
  const body = (items, pad) =>
    items
      .map((it) => {
        if (it.kind === 'path') {
          return `${pad}<path\n${pad}    android:fillColor="${argb(colour(it.role))}"${it.evenodd ? `\n${pad}    android:fillType="evenOdd"` : ''}\n${pad}    android:pathData="${it.d}" />`;
        }
        return `${pad}<group android:translateX="${num(it.tx)}" android:translateY="${num(it.ty)}">\n${body(it.items, pad + '    ')}\n${pad}</group>`;
      })
      .join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${widthDp}dp"
    android:height="${heightDp}dp"
    android:viewportWidth="${num(w)}"
    android:viewportHeight="${num(hgt)}">
    <group android:translateX="${num(-minX)}" android:translateY="${num(-minY)}">
${body(tree, '        ')}
    </group>
</vector>
`;
}

// ---------- Types ----------
function reactTypes(componentNames) {
  const decls = componentNames.map((n) => `export declare function ${n}(props: LynkOmniIconProps): ReactElement;`).join('\n');
  return `// ${GENERATED}
import type { ReactElement, SVGProps } from 'react';

export type LynkOmniIconProps = SVGProps<SVGSVGElement>;

${decls}
`;
}

function brandTypes(ids) {
  const union = (xs) => xs.map((x) => `'${x}'`).join(' | ');
  return `// ${GENERATED}
export type BrandAssetId = ${union(ids)};
export type BrandVariant = ${union(ALL_VARIANTS)};
export type BrandTheme = ${union(THEME_VARIANTS)};

export interface BrandVariantFiles {
  /** Path inside the package, e.g. "svg/lynkomni-logo-light.svg". */
  svg: string;
  /** React component name exported by the package. */
  react: string;
  /** Android drawable resource name (without .xml). */
  android: string;
  /** iOS asset catalogue image name. */
  ios: string;
}

export interface BrandAsset {
  kind: 'emblem' | 'logo' | 'wordmark';
  component: string;
  accessibleName: string;
  minWidthPx: number;
  viewBox: [number, number, number, number];
  variants: Record<BrandVariant, BrandVariantFiles>;
  /** Component that follows the platform theme tokens automatically. */
  auto: { react: string };
}

export interface BrandThemeColours {
  ink: string;
  accent: string;
  backgrounds: Record<string, string>;
}

export declare const brand: {
  schema: 1;
  package: string;
  themes: Record<BrandTheme, BrandThemeColours>;
  assets: Record<BrandAssetId, BrandAsset>;
};

export default brand;
`;
}

// ---------- iOS asset catalogue ----------
const iosInfo = { author: 'xcode', version: 1 };
const json = (o) => JSON.stringify(o, null, 2) + '\n';

// ---------- Main ----------
export function build({ root = ROOT, outDir = join(root, 'dist') } = {}) {
  const { manifest, themes } = loadConfig(root);
  const files = new Map(); // relative path -> string
  const core = { schema: 1, package: manifest.package, themes, assets: {} };
  const componentNames = [];

  for (const asset of manifest.assets) {
    const { tree, vb } = loadAsset(root, asset, themes);
    const lower = `lynkomni-${asset.id}`;
    const snake = `lynkomni_${asset.id}`;
    const entry = {
      kind: asset.kind,
      component: asset.component,
      accessibleName: asset.accessibleName,
      minWidthPx: asset.minWidthPx,
      viewBox: vb,
      variants: {},
      auto: { react: asset.component + SUFFIX.auto },
    };

    for (const variant of ALL_VARIANTS) {
      const colour = (role) => colourFor(variant, role, themes);
      const svgName = `${lower}-${variant}.svg`;
      const reactName = asset.component + SUFFIX[variant];
      const androidName = `${snake}_${variant.replace('-', '_')}`;
      const iosName = `${lower}-${variant}`;
      const svg = svgOf(tree, vb, asset.accessibleName, colour);

      files.set(`svg/${svgName}`, svg);
      files.set(`react/${reactName}.js`, reactOf(reactName, tree, vb, asset.accessibleName, colour, false));
      files.set(`react/${reactName}.d.ts`, `export { ${reactName} as default, ${reactName} } from './index.js';\n`);
      files.set(`android/res/drawable/${androidName}.xml`, androidOf(tree, vb, colour));
      files.set(`ios/LynkOmniBrand.xcassets/${iosName}.imageset/${svgName}`, svg);
      files.set(
        `ios/LynkOmniBrand.xcassets/${iosName}.imageset/Contents.json`,
        json({
          images: [{ filename: svgName, idiom: 'universal' }],
          info: iosInfo,
          properties: { 'preserves-vector-representation': true, ...(variant === 'mono' ? { 'template-rendering-intent': 'template' } : {}) },
        }),
      );
      componentNames.push(reactName);
      entry.variants[variant] = { svg: `svg/${svgName}`, react: reactName, android: androidName, ios: iosName };
    }

    // Themed component: reads the platform design tokens (--logo-ink, --brand-primary).
    const autoName = asset.component + SUFFIX.auto;
    files.set(`react/${autoName}.js`, reactOf(autoName, tree, vb, asset.accessibleName, (role) => themes.light[role], true));
    files.set(`react/${autoName}.d.ts`, `export { ${autoName} as default, ${autoName} } from './index.js';\n`);
    componentNames.push(autoName);

    if (asset.id === 'emblem') files.set('web/favicon.svg', faviconSvg(tree, vb, themes));
    core.assets[asset.id] = entry;
  }

  componentNames.sort();
  files.set(
    'react/index.js',
    `// ${GENERATED}\n` + componentNames.map((n) => `export { ${n} } from './${n}.js';`).join('\n') + '\n',
  );
  files.set('react/index.d.ts', reactTypes(componentNames));
  files.set('ios/LynkOmniBrand.xcassets/Contents.json', json({ info: iosInfo }));
  files.set(
    'brand/index.js',
    `// ${GENERATED}\nexport const brand = Object.freeze(${JSON.stringify(core, null, 2)});\n\nexport default brand;\n`,
  );
  files.set('brand/index.d.ts', brandTypes(manifest.assets.map((a) => a.id)));

  core.icons = addIconFiles(root, files);   // product marks, status icons, core UI icons

  // Checksums let the platform repo prove it holds exactly this release (brand.lock.json).
  const sums = {};
  for (const [path, content] of [...files].sort(([a], [b]) => (a < b ? -1 : 1))) {
    sums[path] = { sha256: createHash('sha256').update(content).digest('hex'), bytes: Buffer.byteLength(content) };
  }
  files.set('brand.json', json({ ...core, files: sums }));

  rmSync(outDir, { recursive: true, force: true });
  for (const [path, content] of files) {
    const full = join(outDir, path);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, content);
  }
  return { files: [...files.keys()].sort(), outDir };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { files, outDir } = build();
  console.log(`Built ${files.length} files into ${outDir}`);
}
