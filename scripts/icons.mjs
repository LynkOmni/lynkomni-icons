// Product marks, status icons and core UI icons. Separate from the logo pipeline: these are one-colour outline icons
// on a 24 grid that take the surrounding text colour (currentColor), so they follow every theme with no variants.
// Manifest: brand/icons.v1.json. Sources: src/{states,ui,products,lowlit}/lynkomni-*.svg. No dependencies.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const SVG_NS = 'http://www.w3.org/2000/svg';
const GENERATED = 'Generated by @lynkomni/icons (scripts/icons.mjs). Do not edit by hand.';
const GROUPS = { states: 'status-', ui: 'ui-', products: 'product-', lowlit: 'lit-' };
export const STATUS_IDS = ['status-queued', 'status-sent', 'status-accepted', 'status-confirmed', 'status-failed'];
const BUDGET_BYTES = 700;
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

export function loadIcons(root) {
  const m = JSON.parse(readFileSync(join(root, 'brand/icons.v1.json'), 'utf8'));
  const icons = m.icons.map((i) => {
    const text = readFileSync(join(root, i.source), 'utf8');
    const d = [...text.matchAll(/<path d="([^"]+)"\/>/g)].map((x) => x[1]);
    return { ...i, text, d };
  });
  return { manifest: m, icons };
}

/** Returns a list of problems; empty means every icon passes the gates. */
export function checkIcons(root) {
  const { manifest, icons } = loadIcons(root);
  const bad = [];
  const ids = new Set();
  const shapes = new Map();
  for (const i of icons) {
    const where = i.id;
    if (!/^[a-z]+(-[a-z]+)+$/.test(i.id)) bad.push(`${where}: id must be lowercase with hyphens`);
    if (ids.has(i.id)) bad.push(`${where}: duplicate id`);
    ids.add(i.id);
    if (!GROUPS[i.group]) bad.push(`${where}: unknown group ${i.group}`);
    else if (!i.id.startsWith(GROUPS[i.group])) bad.push(`${where}: id must start with ${GROUPS[i.group]}`);
    if (i.source !== `src/${i.group}/lynkomni-${i.id}.svg`) bad.push(`${where}: source must be src/${i.group}/lynkomni-${i.id}.svg`);
    if (!i.accessibleName) bad.push(`${where}: needs an accessibleName`);
    if (Buffer.byteLength(i.text) > BUDGET_BYTES) bad.push(`${where}: over the ${BUDGET_BYTES} byte budget`);
    // Safe SVG: only an svg element holding path elements, no scripts, styles, links, images, events or external references.
    if (/<(script|style|image|use|a|foreignObject|text|filter|animate|set)\b/i.test(i.text)) bad.push(`${where}: forbidden element`);
    if (/\son[a-z]+\s*=|href\s*=|xlink|url\(|javascript:|<!ENTITY|<!DOCTYPE/i.test(i.text)) bad.push(`${where}: forbidden attribute or reference`);
    const head = `<svg xmlns="${SVG_NS}" viewBox="0 0 ${manifest.grid} ${manifest.grid}" fill="none" stroke="currentColor" stroke-width="${manifest.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">`;
    if (!i.text.startsWith(head)) bad.push(`${where}: must use the standard ${manifest.grid} grid outline header`);
    if (/#[0-9a-fA-F]{3,8}\b|rgb\(|hsl\(/.test(i.text)) bad.push(`${where}: no colours in an icon, it uses currentColor`);
    if (i.d.length !== 1) bad.push(`${where}: exactly one path expected`);
    else {
      const nums = [...i.d[0].matchAll(/-?\d+(\.\d+)?/g)].map((n) => Number(n[0]));
      if (!/^[MmLlHhVvCcSsQqTtAaZz0-9 .,-]+$/.test(i.d[0])) bad.push(`${where}: path has unexpected characters`);
      if (nums.some((n) => Number.isNaN(n))) bad.push(`${where}: bad number in path`);
      const key = i.d[0];
      if (shapes.has(key) && !(i.id === 'ui-check' && shapes.get(key) === 'status-accepted')) bad.push(`${where}: same shape as ${shapes.get(key)}`);
      shapes.set(key, i.id);
    }
  }
  for (const s of STATUS_IDS) if (!ids.has(s)) bad.push(`missing status icon ${s}`);
  const statusShapes = new Set(icons.filter((i) => STATUS_IDS.includes(i.id)).map((i) => i.d[0]));
  if (statusShapes.size !== STATUS_IDS.length) bad.push('status icons must each have a different shape, so state is never shown by colour alone');
  return bad;
}

const camel = (id) => id.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');

function svgOf(i) {
  return i.text;
}

function reactOf(i, name) {
  return `// ${GENERATED}
import { createElement as h } from 'react';

/** Decorative by default (aria-hidden). Pass aria-label (and role="img") where the icon carries meaning without text. */
export function ${name}(props) {
  return h(
    'svg',
    { xmlns: '${SVG_NS}', viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', strokeWidth: 2, strokeLinecap: 'round', strokeLinejoin: 'round', 'aria-hidden': 'true', focusable: 'false', ...props },
    h('path', { d: ${JSON.stringify(i.d[0])} }),
  );
}

export default ${name};
`;
}

function androidOf(i) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:strokeColor="#FF000000"
        android:strokeWidth="2"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="${esc(i.d[0])}"/>
</vector>
`;
}

/** Adds every icon output to the build's file map and returns the index that goes into brand.json. */
export function addIconFiles(root, files) {
  const { icons } = loadIcons(root);
  const problems = checkIcons(root);
  if (problems.length) throw new Error('icon gates failed:\n' + problems.join('\n'));
  const index = {};
  const names = [];
  for (const i of icons) {
    const name = camel(i.id) + 'Icon';
    const file = `lynkomni-icon-${i.id}`;
    files.set(`icons/${file}.svg`, svgOf(i));
    files.set(`icons/react/${name}.js`, reactOf(i, name));
    files.set(`icons/react/${name}.d.ts`, `export { ${name} as default, ${name} } from './index.js';\n`);
    files.set(`android/res/drawable/lynkomni_icon_${i.id.replace(/-/g, '_')}.xml`, androidOf(i));
    files.set(`ios/LynkOmniIcons.xcassets/${file}.imageset/${file}.svg`, svgOf(i));
    files.set(
      `ios/LynkOmniIcons.xcassets/${file}.imageset/Contents.json`,
      JSON.stringify({ images: [{ filename: `${file}.svg`, idiom: 'universal' }], info: { author: 'xcode', version: 1 }, properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' } }, null, 2) + '\n',
    );
    names.push(name);
    index[i.id] = { group: i.group, accessibleName: i.accessibleName, svg: `icons/${file}.svg`, react: name, android: `lynkomni_icon_${i.id.replace(/-/g, '_')}`, ios: file };
  }
  names.sort();
  files.set('icons/react/index.js', `// ${GENERATED}\n` + names.map((n) => `export { ${n} } from './${n}.js';`).join('\n') + '\n');
  files.set(
    'icons/react/index.d.ts',
    `// ${GENERATED}\nimport type { ReactElement, SVGProps } from 'react';\n\nexport type LynkOmniIconProps = SVGProps<SVGSVGElement>;\n\n` +
      names.map((n) => `export declare function ${n}(props: LynkOmniIconProps): ReactElement;`).join('\n') + '\n',
  );
  files.set('ios/LynkOmniIcons.xcassets/Contents.json', JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2) + '\n');
  return index;
}
